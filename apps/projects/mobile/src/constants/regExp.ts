/**
 * 正则表达式集合
 */

export const PATTERN_MAPS = {
  //包含 字母、数字、符号 其中二种以上字符集，长度8-20位
  password:
    /^(?=(?:[^a-zA-Z]*[a-zA-Z]){1})(?=(?:[^0-9]*[0-9]){1})(?!.*\s).{8,20}$|^(?=(?:[^a-zA-Z]*[a-zA-Z]){1})(?=(?:[^!@#$%^&*()_+\-=\[\]{};':"\\|,.<>\/?]*[!@#$%^&*()_+\-=\[\]{};':"\\|,.<>\/?]){1})(?!.*\s).{8,20}$|^(?=(?:[^0-9]*[0-9]){1})(?=(?:[^!@#$%^&*()_+\-=\[\]{};':"\\|,.<>\/?]*[!@#$%^&*()_+\-=\[\]{};':"\\|,.<>\/?]){1})(?!.*\s).{8,20}$/,
  email: /^[\w-]+(\.[\w-]+)*@[\w-]+(\.[\w-]+)+$/,
  phone: /^1[3|4|5|6|7|8|9][0-9]{9}$/,
  phoneAndEmail: /^(1[3|4|5|6|7|8|9][0-9]{9})|([\w-]+(\.[\w-]+)*@[\w-]+(\.[\w-]+)+)$/,
  tel: /^((0\d{2,3})-)?(\d{7,8})(-(\d{3,}))?$/, // 座机
  smsCode: /^\d{6}$/,
  money: /^\d*(?:\.\d{0,2})?$/,
  weight: /^\d*(?:\.\d{0,3})?$/,
  quantity: /^[1-9]+[0-9]*$/, // 数量，大于等于1的正整数
  lengthReg: /^[a-zA-Z\d]{8,20}$/,
  wordReg: /^(?=.*[a-z])(?=.*[A-Z])(?=.*[0-9])[a-zA-Z\d]*$/,
}
