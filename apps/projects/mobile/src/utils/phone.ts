export const checkStrict = (phone) => {
  // mobileNum = mobileNum.trim()
  /**
   * 中国移动：China Mobile
   * 134(0-8)、135、136、137、138、139、144(物)、147、148(物)、150、151、152、157、158、159、165(虚)、172(物)、178、182、183、184、187、188、195、197、198
   */
  let flag1 = /^1(34[0-8]|(3[5-9]|4[478]|5[0-27-9]|65|7[28]|8[2-478]|9[578])\d)\d{7}$/.test(phone)
  /**
   * 中国联通：China Unicom
   * 130、131、132、140(物)、145、146(物)、155、156、166、167(虚)、175、176、185、186、196(5G)
   */
  let flag2 = /^1(3[0-2]|4[56]|5[56]|6[67]|7[56]|8[56]|96)\d{8}$/.test(phone)
  /**
   * 中国电信：China Telecom
   * 133、141(物)、149(物)、153、162(虚)、173、177、180、181、189、190(5G)、191、193、199
   */
  let flag3 = /^1(33|4[19]|53|62|7[37]|8[019]|9[0139])\d{8}$/.test(phone)
  /**
   * 广电
   * 192(5G)
   */
  let flag4 = /^192\d{8}$/.test(phone)
  /**
   * 大陆地区固话及小灵通
   */
  let flag5 = /^(0{1,2}\d{2,3}|400)-?\d{7,8}$/.test(phone)
  /**
   * 虚拟运营商
   * 电信：1700、1701、1702、1740(0-5)(卫)
   * 移动：1703、1705、1706
   * 联通：1704、1707、1708、1709、171（0-9）
   * 卫星通信：1349
   */
  let flag6 = /^1((7[01][0-9]|349)\d|740[0-5])\d{6}$/.test(phone)
  return flag1 || flag2 || flag3 || flag4 || flag5 || flag6
}
